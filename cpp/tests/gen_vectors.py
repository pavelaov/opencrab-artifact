def trunc_case(name: str, k: int, L: int, f: int, xs: list, rs: list, rng: np.random.Generator) -> dict:
    M = len(xs)
    r = np.array([int(v) & ((1 << k) - 1) for v in rs], dtype=np.uint64)
    m0, m1 = trunc.trunc_material_from_mask(r, f, L, rng, k)
    x_ring = np.array([int(v) & ((1 << k) - 1) for v in xs], dtype=np.uint64)
    x0, x1 = sharing.share_k(x_ring, k, rng)
    y = ring.reduce_k(ring.add(trunc.trunc_open_share(x0, m0, 0), trunc.trunc_open_share(x1, m1, 1)), k)
    o0 = trunc.trunc_faithful_eval(m0, y, 0)
    o1 = trunc.trunc_faithful_eval(m1, y, 1)
    z = ring.reduce_k(ring.add(o0, o1), k)
    expected = [int(v) >> f for v in xs]  # floor division of the signed value
    for m in range(M):
        got = to_signed_k(int(z[m]), k)
        assert got == expected[m], "python trunc self-check failed: %s x=%d got %d want %d" % (name, xs[m], got, expected[m])
        ref = trunc.reference_trunc_small(k, L, f, int(xs[m]), int(r[m]))
        assert ref == expected[m], "python reference_trunc_small disagrees"
    return {
        "name": name, "k": k, "L": L, "f": f, "M": M,
        "x_signed": [str(int(v)) for v in xs], "r": slist(r),
        "x0": slist(x0), "x1": slist(x1), "y": slist(y),
        "material0": m0.to_bytes().hex(), "material1": m1.to_bytes().hex(),
        "out0": slist(o0), "out1": slist(o1),
        "expected_signed": [str(v) for v in expected],
    }


def gen_trunc(rng: np.random.Generator) -> dict:
    cases = []
    cases.append(trunc_case("regression_k8_L6_f3", 8, 6, 3, [-13], [37], rng))
    cases.append(trunc_case("small_k8_L6_f3_sweep", 8, 6, 3, [-32, -31, -1, 0, 1, 7, 8, 31],
                            [int(v) for v in rng.integers(0, 256, size=8)], rng))
    L, f = 40, 16
    xs = []
    for mag in (20, 24, 28, 32, 36, 39):
        for _ in range(3):
            v = int(rng.integers(0, 1 << mag))
            xs.append(v if rng.random() < 0.5 else -v)
    xs += [(1 << (L - 1)) - 1, -((1 << (L - 1)) - 1), -(1 << (L - 1)), 0, 1, -1, 65535, -65536, -65537]
    rs = [int(v) for v in rng.integers(0, 1 << 64, size=len(xs), dtype=np.uint64)]
    cases.append(trunc_case("native_k64_L40_f16", 64, L, f, xs, rs, rng))
    L2 = 46
    xs2 = [int(rng.integers(0, 1 << 44)) * (1 if i % 2 else -1) for i in range(6)] + [(1 << 45) - 1, -(1 << 45)]
    rs2 = [int(v) for v in rng.integers(0, 1 << 64, size=len(xs2), dtype=np.uint64)]
    cases.append(trunc_case("smollm_k64_L46_f16", 64, L2, 16, xs2, rs2, rng))
    return {
        "format": "opencrab2-trunc-vectors-v1",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.lowlevel.trunc)",
        "material_layout": "OC2TRN01 container with DCF keys in the binding layout (wire version 2)",
        "online": "P0 adds a = 2^(L-1); open y = x' + r; [z] = (y >> f) 1{P0} - [r >> f] - [b] + 2^(k-f) [w] - 2^(L-1-f) 1{P0}",
        "cases": cases,
    }


