def gen_prg(rng: np.random.Generator) -> dict:
    cases = []
    seeds = [bytes(range(16))] + [rng.integers(0, 256, size=16, dtype=np.uint8).tobytes() for _ in range(16)]
    for seed in seeds:
        out = prg.expand_bytes(seed)
        assert len(out) == 64
        sL, sR, vL, vR, tL, tR = prg.expand(prg.seeds_from_bytes(seed))
        cases.append({
            "seed": seed.hex(),
            "out": out.hex(),
            "sL": sL.reshape(-1).view(np.uint8).tobytes().hex() if False else np.ascontiguousarray(sL, dtype="<u8").tobytes().hex(),
            "sR": np.ascontiguousarray(sR, dtype="<u8").tobytes().hex(),
            "vL": s64(vL[0]), "vR": s64(vR[0]), "tL": int(tL[0]), "tR": int(tR[0]),
        })
    return {
        "format": "opencrab2-prg-vectors-v1",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.lowlevel.prg)",
        "key": prg.FIXED_KEY.hex(),
        "layout": "out = concat_j AES_K(s xor c_j) xor s; sL=out[0:16] sR=out[16:32] vL=LE64(out[32:40]) vR=LE64(out[40:48]) tL=out[48]&1 tR=out[49]&1",
        "cases": cases,
    }


