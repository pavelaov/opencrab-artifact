U64 = np.uint64
MASK64 = (1 << 64) - 1


def s64(v) -> str:
    """Decimal string of a uint64 (or array element)."""
    return str(int(v))


def slist(arr) -> list:
    return [s64(v) for v in np.asarray(arr, dtype=np.uint64).reshape(-1)]


def to_signed_k(v: int, k: int) -> int:
    v &= (1 << k) - 1
    return v - (1 << k) if v >= (1 << (k - 1)) else v


def write(path: str, obj: dict) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(obj, fh, indent=1, sort_keys=False)
        fh.write("\n")
    print("wrote", path)


