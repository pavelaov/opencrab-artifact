def gen_dcf(rng: np.random.Generator) -> dict:
    cases = []
    T = 68720050177
    for n_bits in (8, 16, 32, 64):
        for P in (1, 2, 3):
            for modulus in (None, T, 17):
                if modulus == 17 and n_bits != 8:
                    continue
                M = 5
                mask = (1 << n_bits) - 1
                alpha = rng.integers(0, 1 << 64, size=M, dtype=np.uint64) & U64(mask)
                if modulus is None:
                    beta = rng.integers(0, 1 << 64, size=(M, P), dtype=np.uint64)
                else:
                    beta = rng.integers(0, modulus, size=(M, P), dtype=np.uint64)
                # evaluation points: alpha, alpha-1, alpha+1 (mod 2^n), random, 0
                x = np.array([int(alpha[0]),
                              (int(alpha[1]) - 1) & mask,
                              (int(alpha[2]) + 1) & mask,
                              int(rng.integers(0, 1 << 64, dtype=np.uint64)) & mask,
                              0], dtype=np.uint64)
                k0, k1 = dcf.gen_dcf_batch(alpha, beta, n_bits, rng, modulus=modulus)
                o0 = dcf.eval_dcf_batch(k0, x)
                o1 = dcf.eval_dcf_batch(k1, x)
                rec = dcf.reconstruct_dcf(o0, o1, modulus)
                expect = np.zeros((M, P), dtype=np.uint64)
                for m in range(M):
                    if int(x[m]) < int(alpha[m]):
                        expect[m] = beta[m] if modulus is None else beta[m] % U64(modulus)
                assert np.array_equal(rec, expect), "python DCF self-check failed"
                cases.append({
                    "name": "%s_n%d_p%d" % ("ring" if modulus is None else "mod%d" % modulus, n_bits, P),
                    "n_bits": n_bits, "P": P, "M": M, "modulus": s64(0 if modulus is None else modulus),
                    "alpha": slist(alpha), "beta": slist(beta), "x": slist(x),
                    "key0": k0.to_bytes().hex(), "key1": k1.to_bytes().hex(),
                    "out0": slist(o0), "out1": slist(o1), "expected": slist(expect),
                })
    return {
        "format": "opencrab2-dcf-vectors-v1",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.lowlevel.dcf)",
        "key_layout": "binding layout, wire version 2: u8 version, u8 party, u8 n_bits, u8 P, u64 LE M, u64 LE modulus, raw arrays (both implementations)",
        "convert": "component-specific Convert words, one set of words per payload component (paper, Section 5.3)",
        "description": "beta, out0, out1, expected are row-major M*P; party 1 negates its share in the payload group",
        "cases": cases,
    }


