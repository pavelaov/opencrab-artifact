_DTYPE_CODE = {"<u8": 1, "<i8": 2, "<f8": 3, "|u1": 4, "<i4": 5}
_DTYPE_BY_CODE = {v: k for k, v in _DTYPE_CODE.items()}


def tagged(obj) -> dict:
    """Language-neutral description of a codec value (exact: ints as decimal strings, floats as IEEE-754 big-endian hex)."""
    import struct
    if obj is None:
        return {"t": "none"}
    if isinstance(obj, bool):
        return {"t": "bool", "v": bool(obj)}
    if isinstance(obj, (bytes, bytearray)):
        return {"t": "bytes", "hex": bytes(obj).hex()}
    if isinstance(obj, np.ndarray):
        return {"t": "nd", "dtype": _DTYPE_CODE[obj.dtype.str], "dims": [int(d) for d in obj.shape],
                "hex": np.ascontiguousarray(obj).tobytes().hex()}
    if isinstance(obj, int):
        return {"t": "int", "v": str(obj)}
    if isinstance(obj, float):
        return {"t": "float", "hex": struct.pack(">d", obj).hex()}
    if isinstance(obj, str):
        return {"t": "str", "v": obj}
    if isinstance(obj, dict):
        return {"t": "dict", "items": [[k, tagged(v)] for k, v in obj.items()]}
    if isinstance(obj, (list, tuple)):
        return {"t": "list", "items": [tagged(v) for v in obj]}
    raise TypeError("cannot describe %r" % type(obj).__name__)


def untagged(d: dict):
    """Inverse of :func:`tagged`."""
    import struct
    t = d["t"]
    if t == "none":
        return None
    if t == "bool":
        return bool(d["v"])
    if t == "bytes":
        return bytes.fromhex(d["hex"])
    if t == "nd":
        return np.frombuffer(bytes.fromhex(d["hex"]), dtype=_DTYPE_BY_CODE[int(d["dtype"])]).reshape([int(v) for v in d["dims"]]).copy()
    if t == "int":
        return int(d["v"])
    if t == "float":
        return struct.unpack(">d", bytes.fromhex(d["hex"]))[0]
    if t == "str":
        return str(d["v"])
    if t == "dict":
        return {str(k): untagged(v) for k, v in d["items"]}
    if t == "list":
        return [untagged(v) for v in d["items"]]
    raise ValueError("unknown tag %r" % (t,))


