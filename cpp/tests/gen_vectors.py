def gen_codec(rng: np.random.Generator) -> dict:
    cases = []
    for name, obj in codec_values(rng):
        payload = hl_channel.encode_payload(obj)
        frame = len(payload).to_bytes(8, "big") + payload
        assert hl_channel.frame_size(obj) == len(frame)
        desc = tagged(obj)
        assert hl_channel.encode_payload(untagged(desc)) == payload, "tagged description does not round trip: %s" % name
        assert hl_channel.encode_payload(hl_channel.decode_payload(payload)) == payload, "codec round trip failed: %s" % name
        cases.append({"name": name, "value": desc, "payload_hex": payload.hex(), "frame_hex": frame.hex()})
    return {
        "format": "opencrab2-codec-vectors-v1",
        "origin": "python",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.highlevel.channel.encode_payload)",
        "tags": "0x01 bytes, 0x02 ndarray, 0x03 dict, 0x04 int, 0x05 float, 0x06 str, 0x07 list, 0x08 none, 0x09 bool",
        "frame": "u64 big-endian payload length, then the payload",
        "value": "tagged description: none | bool v | int v (decimal string) | float hex (IEEE-754 big-endian) | str v | bytes hex | "
                 "nd dtype (wire code) dims hex (little-endian element data) | dict items [[key, value], ...] in wire order | list items",
        "cases": cases,
    }


