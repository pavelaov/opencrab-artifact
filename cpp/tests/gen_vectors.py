KCI_KEYS = 128


def gen_drelu(rng: np.random.Generator, kci_keys: int = KCI_KEYS) -> dict:
    cases = []
    for n_bits in (8, 32, 64):
        for with_product in (False, True):
            lim = 1 << (min(n_bits, 62) - 1)
            xs = [0, -1, 1, lim - 1, -lim] + [int(v) for v in rng.integers(-lim, lim, size=5)]
            M = len(xs)
            r = rng.integers(0, 1 << 64, size=M, dtype=np.uint64)
            m0, m1 = drelu.drelu_material_from_mask(r, n_bits, rng, with_product=with_product)
            x = np.array([v & MASK64 for v in xs], dtype=np.uint64)
            y = ring.add(x, r)
            b0, rb0 = drelu.drelu_eval(m0, y)
            b1, rb1 = drelu.drelu_eval(m1, y)
            bit = [1 if v >= 0 else 0 for v in xs]
            assert [int(v) for v in ring.add(b0, b1)] == bit, "python DReLU self-check failed"
            if with_product:
                assert [int(v) for v in ring.add(rb0, rb1)] == [int(r[i]) * bit[i] for i in range(M)], "python DReLU product self-check failed"
            cases.append({
                "name": "drelu_n%d_p%d" % (n_bits, 2 if with_product else 1),
                "n_bits": n_bits, "with_product": bool(with_product), "M": M,
                "r": slist(r), "x_signed": [str(v) for v in xs], "y": slist(y),
                "material0": m0.to_bytes().hex(), "material1": m1.to_bytes().hex(),
                "b0": slist(b0), "b1": slist(b1),
                "rb0": slist(rb0) if with_product else [], "rb1": slist(rb1) if with_product else [],
                "expected_bit": bit,
            })
    r = rng.integers(0, 1 << 64, size=kci_keys, dtype=np.uint64)
    m0, _m1 = drelu.drelu_material_from_mask(r, 32, rng, with_product=True)
    return {
        "format": "opencrab2-drelu-vectors-v1",
        "origin": "python",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.lowlevel.drelu)",
        "material_layout": "OC2DRL01 container with DCF keys in the binding layout (wire version 2)",
        "online": "open y = x + r; [b] = shares of 1{x >= 0}; [rb] = shares of r 1{x >= 0} (P = 2 only)",
        "cases": cases,
        "kci": {
            "description": "P = 2 DReLU material of party 0 only (beta = (1, r), alpha = r mod 2^n and r + 2^(n-1) mod 2^n) and the masks r: "
                           "the blind attack on the comparison keys (paper, Section 5.3) must recover r in 0 cases, and no level may show a "
                           "correction-word difference equal to +-(r - 1)",
            "n_bits": 32, "M": kci_keys, "party": 0, "r": slist(r), "material": m0.to_bytes().hex(),
        },
    }


