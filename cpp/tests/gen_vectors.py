def gen_telemetry(rng: np.random.Generator) -> dict:
    """Probe samples with the pooled bandwidth and the round-trip time of telemetry.probe_estimate."""
    cap = 1.0e11
    fixed = [
        # a 1 Gbit/s link whose delays fall on a 0.5 ms timer grid: two pings carry one extra tick
        ("one_tick_in_two_pings", 65536, [1.05e-3, 1.56e-3, 1.58e-3], [1.60e-3, 1.59e-3, 1.585e-3]),
        ("one_tick_in_one_ping", 65536, [1.07e-3, 1.59e-3, 1.06e-3], [1.60e-3, 1.61e-3, 1.58e-3]),
        ("floor", 65536, [1.0e-3, 1.1e-3, 1.2e-3], [0.9e-3, 0.95e-3, 1.0e-3]),
        ("floor_exact_zero", 4096, [2.0e-3, 2.0e-3, 2.0e-3], [2.0e-3, 2.0e-3, 2.0e-3]),
        ("above_the_cap", 65536, [1.00e-4, 1.10e-4, 1.20e-4], [1.01e-4, 1.02e-4, 1.03e-4]),
        ("single_sample", 4096, [0.020], [0.050]),
        ("even_two", 16384, [0.040, 0.042], [0.105, 0.109]),
        ("even_four", 65536, [0.0105, 0.0101, 0.0109, 0.0103], [0.0162, 0.0158, 0.0166, 0.0171]),
        ("wan_100mbit", 65536, [0.0405, 0.0401, 0.0409], [0.0458, 0.0454, 0.0462]),
        ("unsorted_five", 1024, [0.0031, 0.0029, 0.0035, 0.0030, 0.0042], [0.0047, 0.0039, 0.0044, 0.0058, 0.0041]),
    ]
    cases = []
    for _ in range(24):
        n = int(rng.integers(1, 6))
        burst = int(rng.choice([1024, 4096, 16384, 65536]))
        rtt = float(rng.choice([2.0e-4, 1.0e-3, 2.0e-2, 8.0e-2]))
        rate = float(rng.choice([2.0e6, 2.0e7, 1.0e8, 1.0e9, 1.0e10]))
        rtts = [rtt * (1.0 + 0.5 * float(rng.random())) for _ in range(n)]
        els = [r + burst * 8.0 / rate * (0.5 + float(rng.random())) for r in rtts]
        if rng.random() < 0.25:                                    # a ping that is later than its own burst
            rtts[int(rng.integers(0, n))] += burst * 8.0 / rate
        fixed.append(("random_%d" % len(fixed), burst, rtts, els))
    for name, burst, rtts, els in fixed:
        bw, rtt = hl_telemetry.probe_estimate(rtts, els, burst)
        cases.append({"name": name, "burst": int(burst), "rtt_s": [float(v) for v in rtts],
                      "elapsed_s": [float(v) for v in els], "bandwidth_bps": bw, "rtt_median_s": rtt,
                      "frame_bandwidth_bps": float(min(bw, cap)), "frame_rtt_s": float(max(rtt, 1e-6))})
    return {
        "format": "opencrab2-telemetry-vectors-v1",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.highlevel.telemetry.probe_estimate)",
        "rule": "rtt_median_s = median(rtt_s); bandwidth_bps = burst * 8 / max(median(elapsed_s) - min(rtt_s), min_net_s); "
                "the median of an even number of samples is the mean of the two middle ones; the frame carries "
                "frame_bandwidth_bps = min(bandwidth_bps, max_bandwidth_bps) and frame_rtt_s = max(rtt_median_s, 1e-6)",
        "comparison": "bandwidth_bps, rtt_median_s, frame_bandwidth_bps and frame_rtt_s to relative 1e-12",
        "min_net_s": float(hl_telemetry.PROBE_MIN_NET_S),
        "max_bandwidth_bps": cap,
        "cases": cases,
    }


def gen_shaper(rng: np.random.Generator) -> dict:
    """WallClockShaper cases: trace, nbytes, wall time, expected delay and serialization.

    Rule: delay = serialization + one-way delay of the state in force when the last byte leaves; bandwidth 0
    = unshaped. Every case is evaluated on a fresh (idle) shaper in both languages.
    """
    from opencrab2.highlevel.channel import WallClockShaper
    traces = [
        [(0.0, 8000.0, 0.010), (1.0, 80000.0, 0.050), (2.0, 0.0, 0.200), (3.0, 800.0, 0.0)],     # slow links, unshaped stretch, zero delay
        [(0.0, 1e6, 0.010), (1.0, 2e6, 0.020)],
        [(0.0, 0.0, 0.030)],
        [(0.0, 5e5, 0.0), (0.25, 0.0, 0.004), (0.5, 2.5e5, 0.008), (4.0, 1e7, 0.001)],
        [(0.5, 64000.0, 0.1), (0.5, 128000.0, 0.2), (2.0, 32000.0, 0.3)],                        # equal start times
    ]
    queries = [(1000, 0.0), (1500, 0.0), (20000, 0.5), (100, 2.5), (0, 0.7), (1, 0.999999), (125000, 0.0),
               (250000, 0.3), (10 ** 7, 1.75), (12345, -1.0), (8, 3.0), (999, 10.0)]
    cases = []
    for ti, tr in enumerate(traces):
        for origin in (0.0, 1000.0):
            for nbytes, w in queries:
                sh = WallClockShaper.from_points(tr, origin)
                cases.append({"trace": ti, "points": [list(p) for p in tr], "origin": origin, "nbytes": int(nbytes),
                              "wall_s": origin + w, "delay_s": float(sh.delay_for(nbytes, origin + w)),
                              "serialization_s": float(sh.serialization_time(nbytes, origin + w))})
    for _ in range(40):
        n = int(rng.integers(1, 6))
        ts = np.sort(rng.uniform(0.0, 5.0, size=n))
        tr = [(float(ts[i]), float(rng.choice([0.0, 8e3, 6.4e4, 1e6, 2.5e7])), float(rng.choice([0.0, 0.0005, 0.02, 0.15])))
              for i in range(n)]
        nbytes, w = int(rng.integers(0, 400000)), float(rng.uniform(-0.5, 6.0))
        sh = WallClockShaper.from_points(tr, 0.0)
        cases.append({"trace": "random", "points": [list(p) for p in tr], "origin": 0.0, "nbytes": nbytes, "wall_s": w,
                      "delay_s": float(sh.delay_for(nbytes, w)), "serialization_s": float(sh.serialization_time(nbytes, w))})
    return {"rule": "delay = serialization + one_way_delay of the state in force when the last byte leaves; "
                    "bandwidth 0 = unshaped; fresh shaper per case", "generator": "python", "cases": cases}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(HERE, "vectors"))
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--kci-keys", type=int, default=KCI_KEYS,
                    help="P = 2 DReLU keys in the KEY_COMPONENT_INDEPENDENCE batch of drelu_vectors.json")
    ap.add_argument("--only", default="", help="comma separated names of the vector files to write (default: all)")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    rng = np.random.default_rng(args.seed)
    # the first five share one generator: each is computed in this order (so that its content never
    # depends on the selection) up to the last one wanted
    shared = [("prg", gen_prg), ("dcf", gen_dcf), ("trunc", gen_trunc), ("r2f", gen_r2f),
              ("controller", lambda r: gen_controller(r, np.random.default_rng(args.seed + 4)))]
    # the files below draw from their own generators, so adding one does not change the others
    own = [("drelu", lambda: gen_drelu(np.random.default_rng(args.seed + 1), args.kci_keys)),
           ("codec", lambda: gen_codec(np.random.default_rng(args.seed + 2))),
           ("contract", gen_contract),
           ("costmodel", gen_costmodel),
           ("shaper", lambda: gen_shaper(np.random.default_rng(args.seed + 3))),
           ("telemetry", lambda: gen_telemetry(np.random.default_rng(args.seed + 5)))]
    names = [n for n, _ in shared] + [n for n, _ in own]
    only = [n.strip() for n in args.only.split(",") if n.strip()] or names
    unknown = [n for n in only if n not in names]
    if unknown:
        print("GEN_VECTORS_ONLY: unknown vector names %r; known: %s" % (unknown, ", ".join(names)))
        return 2
    last = max([i for i, (n, _) in enumerate(shared) if n in only], default=-1)
    for name, fn in shared[:last + 1]:
        doc = fn(rng)
        if name in only:
            write(os.path.join(args.out, name + "_vectors.json"), doc)
    for name, fn in own:
        if name in only:
            write(os.path.join(args.out, name + "_vectors.json"), fn())
    return 0


if __name__ == "__main__":
    sys.exit(main())
