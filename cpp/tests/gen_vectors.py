def r2f_case(name: str, k: int, t: int, a0s: list, a1s: list, rs: list, rng: np.random.Generator) -> dict:
    a0 = np.array([int(v) & ((1 << k) - 1) for v in a0s], dtype=np.uint64)
    a1 = np.array([int(v) & ((1 << k) - 1) for v in a1s], dtype=np.uint64)
    r = np.array([int(v) & ((1 << k) - 1) for v in rs], dtype=np.uint64)
    m0, m1 = r2f.r2f_material_from_mask(r, t, rng, k)
    y = ring.reduce_k(ring.add(r2f.r2f_open_share(a0, m0, 0), r2f.r2f_open_share(a1, m1, 1)), k)
    o0 = r2f.r2f_eval(m0, y, 0)
    o1 = r2f.r2f_eval(m1, y, 1)
    u = ring.reduce_k(ring.add(a0, a1), k)
    expected = r2f.signed_mod(u, t, k)
    z = (o0.astype(object) + o1.astype(object)) % t
    for m in range(len(a0s)):
        assert int(z[m]) == int(expected[m]), "python r2f self-check failed: %s" % name
    return {
        "name": name, "k": k, "t": s64(t), "M": len(a0s),
        "a0": slist(a0), "a1": slist(a1), "r": slist(r), "y": slist(y),
        "material0": m0.to_bytes().hex(), "material1": m1.to_bytes().hex(),
        "out0": slist(o0), "out1": slist(o1), "expected": slist(expected),
    }


def gen_r2f(rng: np.random.Generator) -> dict:
    cases = []
    cases.append(r2f_case("audit_k8_t17", 8, 17, [255, 128], [2, 129], [int(v) for v in rng.integers(0, 256, size=2)], rng))
    cases.append(r2f_case("small_k8_t13_sweep", 8, 13, list(range(0, 256, 23)), [int(v) for v in rng.integers(0, 256, size=12)],
                          [int(v) for v in rng.integers(0, 256, size=12)], rng))
    T = 68720050177
    n = 12
    a0 = [int(v) for v in rng.integers(0, 1 << 64, size=n, dtype=np.uint64)]
    a1 = [int(v) for v in rng.integers(0, 1 << 64, size=n, dtype=np.uint64)]
    # force a few signed values: u = a0 + a1 with u chosen
    for i, uval in enumerate([-1, (1 << 63) - 1, -(1 << 63), 0, 1, -(1 << 40)]):
        a1[i] = (uval - a0[i]) & MASK64
    rs = [int(v) for v in rng.integers(0, 1 << 64, size=n, dtype=np.uint64)]
    cases.append(r2f_case("native_k64_t68720050177", 64, T, a0, a1, rs, rng))
    return {
        "format": "opencrab2-r2f-vectors-v1",
        "generator": "cpp/tests/gen_vectors.py (python opencrab2.lowlevel.ring_to_field)",
        "material_layout": "OC2R2F01 container with DCF keys in the binding layout (wire version 2)",
        "cases": cases,
    }


