#!/usr/bin/env python3
"""Cross-language test vectors produced by the Python reference package.

Run with the project interpreter from any directory:

    python cpp/tests/gen_vectors.py [--out cpp/tests/vectors] [--seed 2026] [--only controller,telemetry]

`--only` rewrites the named files alone (names: prg, dcf, trunc, r2f, controller, drelu, codec, contract,
costmodel, shaper, telemetry) and leaves every other file untouched; the content of a file does not depend
on which other files are written.

It imports `opencrab2` from python/ (sys.path is extended relative to this file) and writes

    prg_vectors.json         64-byte MMO expansions of 17 seeds (the fixed seed 00..0f first)
    dcf_vectors.json         DCF key batches generated by Python (binding wire layout: u8 version = 2,
                             u8 party, u8 n_bits, u8 P, u64 LE M, u64 LE modulus, then the raw arrays)
                             with the evaluation points and BOTH parties' output shares, for
                             n in {8, 16, 32, 64}, P in {1, 2, 3}, payload groups Z_2^64 and Z_t
                             (component-specific Convert words)
    drelu_vectors.json       DReLU material (OC2DRL01, P = 1 and P = 2) with the opened y and both
                             parties' output shares, plus one batch of P = 2 keys of one party for the
                             KEY_COMPONENT_INDEPENDENCE attack run by the other language
    trunc_vectors.json       faithful truncation material (OC2TRN01) with shares, the opened y, both
                             parties' outputs and the plaintext floor(x / 2^f); includes the regression
                             (k=8, L=6, f=3, x=-13, r=37) -> -2 and the boundary values
    r2f_vectors.json         ring_to_field material (OC2R2F01) with the counterexamples of the share-wise
                             reduction (q = 256, t = 17: a0 = 255, a1 = 2 and a0 = 128, a1 = 129) and random
                             64-bit inputs under t = 68720050177
    controller_vectors.json  controller decisions (state, candidates, config, explicit survival vector,
                             expected decision) computed by opencrab2.highlevel.controller; instances
                             0 to 29 price one shape (exec_s_per_epoch for every step), instances from 30
                             on carry the per-step costs exec_s_by_epoch and exec_sigma_by_epoch
    telemetry_vectors.json   probe samples (ping times, burst times, burst size) with the pooled bandwidth
                             and the round-trip time of opencrab2.highlevel.telemetry.probe_estimate
    codec_vectors.json      wire codec values of every tag (none 0x08 and bool 0x09 included) with
                             the payload bytes and the framed bytes (u64 BE length prefix)
    contract_vectors.json    numeric contracts (named ones and variants) with their contract hashes
    shaper_vectors.json      WallClockShaper cases (trace, nbytes, wall time, expected delay and serialization
                             time) under the rule shared by the two languages
    costmodel_vectors.json   a fixed coefficient table, shapes and environments with the predicted
                             mean and sigma, the byte, round, message, MAC and material formulas, the
                             fused tournament gate counts and the shared constants of the
                             formula file (calibration/formulas.json)

The same file formats are written by the C++ side (test_vectors --emit DIR writes cpp_codec_vectors.json,
cpp_contract_vectors.json, cpp_costmodel_vectors.json and cpp_drelu_vectors.json) and are checked by
python/tests/test_cross_language.py, so every item is compared in both directions.

Every 64-bit integer is a decimal string (JSON readers cannot hold a uint64 exactly); byte strings
are lower-case hex. The files are deterministic for a given --seed. The C++ side
(tests/test_vectors.cpp) loads them and must reproduce every output share bit for bit; when the
Python package is missing the script exits with code 3 and prints the reason, and the C++ test
skips the parity checks with a clear message.

Design note on the controller vectors: the two languages fit the regime dwell model differently
(Python: hazard = (changes + 1) / (steps + prior); C++: exponential MLE with the prior as one
pseudo observation), so the vectors carry the survival vector explicitly and the C++ test calls
decide_with_survival. Candidates carry c_wait_s = 0 (the Python Candidate has no wait term).
"""
