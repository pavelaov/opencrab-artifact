"""Three-process launcher: isolated dealer, P0 and P1 (paper, Section 7.1, experimental details).

:func:`launch_two_party` spawns three OS processes with the ``spawn`` start
method: the dealer service (``python -m opencrab2.platform.dealer_service``
in ISOLATED_RECIPIENT_BUNDLES mode, streaming recipient-bound bundles that the
parties request by type and count ahead of each epoch), the model owner P0 and
the client P1 (both :func:`opencrab2.highlevel.session.run_session_party`).
Per-recipient HMAC keys are generated by the launcher from the OS CSPRNG; the
dealer reads both from its keys file, each party receives only its own key in
its process arguments, and the keys file is deleted when the launch ends.

Both parties receive the same exogenous trace and the same wall-clock origin
(``origin_wall_s``, a few seconds in the future so that both are ready), so the
link shaper, the public CPU load and the material refill pacer fire at
identical elapsed times on both ends. P0 listens on an ephemeral
loopback port that it publishes through a queue; P1 dials it. The two evidence
records are appended to ``<out_dir>/sessions.jsonl`` (one line per party) and
their paths plus the dealer log are returned.

Options of the measured campaigns (``experiments.run_sessions``):

* ``threads_per_process``: the three child processes are started with
  ``OMP_NUM_THREADS``, ``OPENBLAS_NUM_THREADS`` and ``MKL_NUM_THREADS`` set to
  this value, so that several sessions can run side by side on one host
  without oversubscribing the BLAS pools. Every listening socket (dealer, P0)
  binds port 0, so concurrent launches never collide; the chosen ports are
  returned under ``ports``.
* ``compute_reference`` (default on): when ``cfg.reference_tokens`` is empty
  the launcher loads the public test model, computes the greedy continuation
  of the float reference (erf-GELU, ``experiments.workloads``) and hands it to
  P1 only. P0 receives a copy of the configuration WITHOUT the prompt ids and
  without the reference tokens (it learns the public prompt length only).
  P1 writes ``output_match``, the released and the reference tokens and the
  first mismatching step to its own record and detail file; P0's record
  never holds a token id. The launcher returns the reference margins
  (``reference_margins``) so that a driver can store the margin of a
  mismatching step next to the record.
* ``warm_prime``: both party processes first run an unshaped priming session
  (fixed all-wmask plan, one token) on a :class:`~opencrab2.highlevel.session.WarmStack`
  and then the measured session on the same stack and the same channel, so the
  measured session is a real warm request (installed objects, shared vectors
  and the ledger are reused; ``T_warm_s`` is its measured wall time). The
  priming record goes to ``priming.jsonl``, never to the measured log.
* ``dealer_mode = INSECURE_TEST_ONLY_SHARED_SEED`` is a diagnostic path: the
  launcher then sets ``OPENCRAB2_TEST_ALLOW_INSECURE_DEALER=1`` for the child
  processes and passes ``allow_insecure=True`` to their dealer clients; without
  that they fail closed with ``DEALER_INSECURE_MODE``. Such records are
  DIAGNOSTIC and never security eligible.

What is tested (tests/test_launch.py): a full tiny-model session with the
three processes; both records validate, carry ``dealer_mode ==
ISOLATED_RECIPIENT_BUNDLES``, are security eligible, share the trace hash and
the clock origin, and the keys file is gone afterwards. Design limits: all
three processes share one host (loopback), so CPU contention injected by the
trace loads the dealer as well; the launcher kills every child on a failure
and reports the first exception, it does not retry.
"""

from __future__ import annotations

import dataclasses
import json
import multiprocessing
import os
import secrets
import subprocess
import sys
import threading
import time
import traceback
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from opencrab2.errors import ChannelError, MaterialError, OpenCrabError
from opencrab2.highlevel.contract import contract_by_name
from opencrab2.highlevel.dealer import ENV_ALLOW_INSECURE, MODE_ISOLATED, PROFILE_ID, DealerClient
from opencrab2.highlevel.ledger import MaterialLedger
from opencrab2.highlevel.session import (DEFAULT_FIXED_PLAN, SessionConfig, SessionDealer, load_model,
                                         model_version_of, new_warm_stack, run_session_party)

RECORDS_FILE = "sessions.jsonl"
PRIMING_FILE = "priming.jsonl"
DEALER_START_TIMEOUT_S = 60.0
ORIGIN_LEAD_S = 2.0
THREAD_ENV: Tuple[str, ...] = ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS")
_ENV_LOCK = threading.Lock()


def thread_env(threads_per_process: Optional[int]) -> Dict[str, str]:
    """The BLAS thread cap of a child process as environment variables (``THREAD_ENV``); empty without a cap.

    Shared by every driver that starts party processes on one host (the session launcher and the Web
    driver): two uncapped BLAS pools that run the same large product at the same instant stall each other.
    """
    if threads_per_process is None:
        return {}
    if int(threads_per_process) < 1:
        raise MaterialError("LAUNCH_PARAMS: threads_per_process must be >= 1")
    return {k: str(int(threads_per_process)) for k in THREAD_ENV}


def reference_tokens_for(cfg: SessionConfig, weights: Optional[dict] = None, meta: Optional[dict] = None
                         ) -> Tuple[List[int], List[float]]:
    """(reference greedy tokens, top-1 minus top-2 margins) of the float functionality for ``cfg`` (public test input)."""
    from opencrab2.experiments import workloads
    if weights is None or meta is None:
        weights, meta = load_model(cfg.model, cfg.n_layers)
    toks = workloads.reference_greedy_tokens(weights, meta, cfg.n_layers, list(cfg.prompt_ids), cfg.n_generate)
    margins = workloads.reference_margins(weights, meta, cfg.n_layers, list(cfg.prompt_ids), cfg.n_generate)
    return toks, margins


def _python() -> str:
    return sys.executable


def start_dealer_process(keys_path: str, contract_name: str, setup_id: str, model_version: str, out_dir: str,
                         mode: str = MODE_ISOLATED, refill_bytes_per_s: Optional[float] = None,
                         timeout_s: float = DEALER_START_TIMEOUT_S) -> Tuple[subprocess.Popen, str, int, str]:
    """Spawn the dealer service; returns (process, host, port, log_path)."""
    log_path = os.path.join(out_dir, "dealer.log")
    env = dict(os.environ)
    pydir = str(Path(__file__).resolve().parents[2])
    env["PYTHONPATH"] = pydir + os.pathsep + env.get("PYTHONPATH", "")
    env.setdefault("HF_HUB_OFFLINE", "1")
    cmd = [_python(), "-m", "opencrab2.platform.dealer_service", "--listen", "127.0.0.1:0", "--keys", keys_path,
           "--contract", contract_name, "--setup-id", setup_id, "--model-version", model_version, "--mode", mode]
    if refill_bytes_per_s is not None:
        cmd += ["--refill-bytes-per-s", str(float(refill_bytes_per_s))]
    log = open(log_path, "w", encoding="utf-8", newline="\n")
    proc = subprocess.Popen(cmd, cwd=pydir, env=env, stdout=subprocess.PIPE, stderr=log, text=True)
    deadline = time.time() + timeout_s
    line = ""
    while time.time() < deadline:
        line = proc.stdout.readline() if proc.stdout is not None else ""
        if line or proc.poll() is not None:
            break
    if not line.startswith("LISTENING"):
        proc.kill()
        log.close()
        raise MaterialError(f"DEALER_START_FAILED: dealer service did not report LISTENING (see {log_path})")
    _, host, port = line.split()
    return proc, host, int(port), log_path


def _party_main(party: int, cfg: SessionConfig, trace: Any, origin_wall_s: float, dealer_host: str,
                dealer_port: int, key: bytes, port_q: Any, result_q: Any, journal_path: str, out_path: str,
                host: str, opts: Optional[dict] = None) -> None:   # pragma: no cover (child process)
    """Entry point of a party process: channel, dealer connection, ledger, session(s), record."""
    from opencrab2.highlevel.channel import accept_channel, dial_channel, open_listener
    from opencrab2.platform.dealer_service import DealerServiceClient

    opts = dict(opts or {})
    allow_insecure = True if opts.get("allow_insecure") else None
    warm_prime = bool(opts.get("warm_prime"))
    channel = None
    listen_port = None
    try:
        service = DealerServiceClient(dealer_host, dealer_port, party, key, cfg.contract.contract_hash(), retries=500,
                                      setup_id=str(cfg.setup_id), allow_insecure=allow_insecure)
        binding_d = service.connect()
        model_version = cfg.model_version or str(binding_d["model_version"])
        cfg.model_version = model_version
        cfg.setup_id = str(binding_d["setup_id"])
        weights = meta = None
        if party == 0:
            weights, meta = load_model(cfg.model, cfg.n_layers)       # once, outside every timed boundary
        stack = None
        if warm_prime:
            stack = new_warm_stack(party, model_version, str(cfg.client_key_domain), int(cfg.n_layers), journal_path,
                                   cfg.setup_id, cfg.contract, key, service, profile_id=str(cfg.profile_id),
                                   allow_insecure=allow_insecure)
            ledger = stack.ledger
            dealer: Any = stack.client
        else:
            binding = {"session_id": cfg.session_id, "setup_id": cfg.setup_id, "model_version": model_version,
                       "numeric_contract_hash": cfg.contract.contract_hash(), "profile_id": cfg.profile_id}
            ledger = MaterialLedger(journal_path, binding)
            client = DealerClient(party, ledger, key, cfg.contract, allow_insecure=allow_insecure)
            dealer = SessionDealer(client, service, f"{cfg.session_id}:g0")
        if party == 0:
            lsock, port = open_listener(host, 0)
            listen_port = int(port)
            port_q.put(listen_port)
            channel = accept_channel(lsock, 0, timeout_s=120.0)
        else:
            port = int(port_q.get(timeout=120.0))
            channel = dial_channel(host, port, 1, retries=1500)
        kw: Dict[str, Any] = {"dealer_service": service}
        if party == 0:
            kw.update(weights=weights, meta=meta)
        priming = None
        if warm_prime:
            prime_cfg = dataclasses.replace(
                cfg, policy="B0_fixed", fixed_plan=dict(DEFAULT_FIXED_PLAN), n_generate=1, initial_plan=None,
                session_id=f"{cfg.session_id}-prime", run_id=f"{cfg.run_id}:prime", cancel_after_epoch=None,
                reference_tokens=(list(cfg.reference_tokens)[:1] if cfg.reference_tokens else None),
                trace_id="unshaped-priming", cpu_load_party=None)
            prec = run_session_party(party, prime_cfg, channel, dealer, ledger, None, None,
                                     os.path.join(os.path.dirname(out_path), PRIMING_FILE), warm=stack, **kw)
            priming = {"completed": bool(prec["detail"]["completed"]),
                       "session_wall_s": prec["extra"]["session_wall_s"],
                       "installed": sorted(stack.installed), "install_s": prec["extra"]["install_s"]}
            if not priming["completed"] or not stack.warm:
                raise ChannelError("LAUNCH_PRIMING_FAILED: the priming session did not leave a warm stack")
            # the measured session gets its own shared clock origin, agreed after the priming ended
            if party == 0:
                origin_wall_s = time.time() + float(opts.get("origin_lead_s", ORIGIN_LEAD_S))
                channel.send({"origin_wall_s": float(origin_wall_s)})
            else:
                msg = channel.recv()
                if not isinstance(msg, dict) or not isinstance(msg.get("origin_wall_s"), float):
                    raise ChannelError("LAUNCH_ORIGIN: malformed origin announcement")
                origin_wall_s = float(msg["origin_wall_s"])
            kw["warm"] = stack
        # wait for the shared origin so that both ends start the trace clock together
        now = time.time()
        if origin_wall_s > now:
            time.sleep(origin_wall_s - now)
        rec = run_session_party(party, cfg, channel, dealer, ledger, None, trace, out_path,
                                origin_wall_s=origin_wall_s, **kw)
        result_q.put({"party": party, "ok": True, "record": {k: v for k, v in rec.items() if k not in ("detail",)},
                      "paths": rec.get("paths", {}), "listen_port": listen_port, "summary": {
                          "completed": rec["detail"]["completed"], "cancelled": rec["detail"]["cancelled"],
                          "epochs": len(rec["detail"]["epochs"]), "stalls": rec["detail"]["stalls"],
                          "origin_wall_s": rec["detail"]["origin_wall_s"],
                          "cpu_load_workers": rec["detail"]["cpu_load_workers"],
                          "generated_tokens": rec["detail"].get("generated_tokens"),
                          "output_match": rec.get("output_match"), "warm_start": rec["detail"].get("warm_start"),
                          "priming": priming, "shaped": rec["detail"]["shaped"]}})
        service.close()
        ledger.close()
    except BaseException as exc:   # noqa: BLE001 (reported to the parent)
        result_q.put({"party": party, "ok": False, "error": f"{exc.__class__.__name__}: {exc}",
                      "traceback": traceback.format_exc()})
    finally:
        if channel is not None:
            try:
                channel.close()
            except Exception:
                pass


def launch_two_party(cfg: SessionConfig, trace: Any, out_dir: str, *, host: str = "127.0.0.1",
                     dealer_mode: str = MODE_ISOLATED, timeout_s: float = 1800.0,
                     origin_lead_s: float = ORIGIN_LEAD_S, threads_per_process: Optional[int] = None,
                     compute_reference: bool = True, warm_prime: bool = False,
                     external_dealer: Optional[Tuple[str, int, str]] = None) -> dict:
    """Run one session as three OS processes; returns the evidence record paths and summaries.

    ``external_dealer = (host, port, keys_path)`` runs the two party processes
    against a dealer service that is already listening (for example the C++
    ``opencrab2_dealer``, which speaks the same dialogue) instead of spawning
    the Python one. The keys file holds ``{"0": hex, "1": hex}`` and is left
    in place; that dealer must have been started with ``cfg.setup_id`` (a
    non-empty value), ``cfg.model_version`` and the contract of ``cfg``,
    otherwise HELLO is refused. ``dealer_mode`` then only states what the
    caller expects: an insecure dealer is refused unless it says so.

    ``cfg.model`` must be loadable by P0 (``gpt2`` or ``npz:<path>``);
    ``cfg.model_version`` (when empty, the launcher derives it from the model).
    ``trace`` is a trace dict or None (unshaped). The dealer streams in
    ``dealer_mode`` (ISOLATED by default; the insecure mode is a diagnostic
    path, see the module docstring). ``threads_per_process``,
    ``compute_reference`` and ``warm_prime`` are described in the module
    docstring. The returned dict holds ``records`` (paths), ``record0`` /
    ``record1``, ``summaries``, ``errors``, ``dealer_log``, ``origin_wall_s``,
    ``ports``, ``threads_per_process``, ``warm_prime`` and, when the launcher
    computed it, ``reference_margins``.
    """
    cfg.validate()
    out_dir = str(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    if threads_per_process is not None and int(threads_per_process) < 1:
        raise MaterialError("LAUNCH_PARAMS: threads_per_process must be >= 1")
    if not cfg.session_id:
        cfg.session_id = "sess-" + secrets.token_hex(6)
    if not cfg.run_id:
        cfg.run_id = f"{cfg.session_id}-r{int(cfg.repeat)}"
    result: Dict[str, Any] = {"records": [], "summaries": {}, "errors": {}, "ports": {},
                              "threads_per_process": threads_per_process, "warm_prime": bool(warm_prime)}
    model_version = cfg.model_version
    need_reference = bool(compute_reference) and cfg.reference_tokens is None and len(cfg.prompt_ids or []) > 0
    if not model_version or need_reference:
        W, meta = load_model(cfg.model, cfg.n_layers)
        if not model_version:
            model_version = model_version_of(meta)
            cfg.model_version = model_version
        if need_reference:
            toks, margins = reference_tokens_for(cfg, W, meta)
            cfg.reference_tokens = toks
            result["reference_margins"] = margins
        del W
    # P0 never receives the client's prompt ids or the reference continuation: only the public length
    cfg0 = dataclasses.replace(cfg, prompt_ids=[], prompt_len=cfg.effective_prompt_len(), reference_tokens=None)
    if external_dealer is not None:
        ext_host, ext_port, ext_keys = str(external_dealer[0]), int(external_dealer[1]), str(external_dealer[2])
        if not cfg.setup_id:
            raise MaterialError("LAUNCH_PARAMS: an external dealer needs a non-empty cfg.setup_id")
        try:
            with open(ext_keys, "r", encoding="utf-8") as fh:
                raw_keys = json.load(fh)
            keys = {r: bytes.fromhex(str(raw_keys[str(r)])) for r in (0, 1)}
        except (OSError, ValueError, KeyError, TypeError) as exc:
            raise MaterialError(f"LAUNCH_PARAMS: cannot read the dealer keys file: {exc.__class__.__name__}") from None
        if any(len(k) < 16 for k in keys.values()):
            raise MaterialError("LAUNCH_PARAMS: a dealer key is shorter than 16 bytes")
        keys_path = None
    else:
        keys = {0: secrets.token_bytes(32), 1: secrets.token_bytes(32)}
        keys_path = os.path.join(out_dir, f"dealer-keys-{secrets.token_hex(4)}.json")
        from opencrab2.platform.dealer_service import write_keys
        write_keys(keys_path, keys)                          # mode 0600 on POSIX
    out_path = os.path.join(out_dir, RECORDS_FILE)
    ctx = multiprocessing.get_context("spawn")
    dealer_proc = None
    procs: List[Any] = []
    insecure = dealer_mode != MODE_ISOLATED
    env_over: Dict[str, str] = thread_env(threads_per_process)
    if insecure:
        env_over[ENV_ALLOW_INSECURE] = "1"
    opts = {"allow_insecure": insecure, "warm_prime": bool(warm_prime), "origin_lead_s": float(origin_lead_s)}
    try:
        port_q = ctx.Queue()
        result_q = ctx.Queue()
        # children inherit the environment at start: set the thread caps (and the diagnostic switch) only around
        # the spawns and restore the launcher's own environment afterwards
        with _ENV_LOCK:
            saved = {k: os.environ.get(k) for k in env_over}
            os.environ.update(env_over)
            try:
                if external_dealer is not None:
                    dhost, dport, dealer_log = ext_host, ext_port, None
                    result["external_dealer"] = True
                else:
                    dealer_proc, dhost, dport, dealer_log = start_dealer_process(
                        keys_path, cfg.contract.name, cfg.setup_id, model_version, out_dir, mode=dealer_mode)
                result["dealer_log"] = dealer_log
                result["ports"]["dealer"] = int(dport)
                origin = time.time() + float(origin_lead_s)
                result["origin_wall_s"] = origin
                for party in (0, 1):
                    journal = os.path.join(out_dir, f"{cfg.session_id}-ledger{party}.jsonl")
                    p = ctx.Process(target=_party_main,
                                    args=(party, cfg0 if party == 0 else cfg, trace, origin, dhost, dport, keys[party],
                                          port_q, result_q, journal, out_path, host, opts),
                                    name=f"opencrab2-party{party}")
                    p.start()
                    procs.append(p)
            finally:
                for k, v in saved.items():
                    if v is None:
                        os.environ.pop(k, None)
                    else:
                        os.environ[k] = v
        got = 0
        deadline = time.time() + float(timeout_s)
        while got < 2 and time.time() < deadline:
            try:
                msg = result_q.get(timeout=1.0)
            except Exception:
                if all(not p.is_alive() for p in procs):
                    try:
                        msg = result_q.get(timeout=2.0)      # a result may still be in the pipe
                    except Exception:
                        break
                else:
                    continue
            got += 1
            party = int(msg["party"])
            if msg.get("ok"):
                result["summaries"][party] = msg["summary"]
                result[f"record{party}"] = msg["record"]
                result["records"].append(msg["paths"].get("record", out_path))
                if msg.get("listen_port") is not None:
                    result["ports"]["p0"] = int(msg["listen_port"])
            else:
                result["errors"][party] = msg.get("error", "unknown")
                result[f"traceback{party}"] = msg.get("traceback", "")
                deadline = min(deadline, time.time() + 30.0)     # the peer cannot finish without this party
        for p in procs:
            p.join(10.0)
    finally:
        for p in procs:
            if p.is_alive():
                p.terminate()
        if dealer_proc is not None:
            dealer_proc.kill()
            try:
                dealer_proc.communicate(timeout=10)
            except Exception:
                pass
        if keys_path is not None:
            try:
                os.remove(keys_path)
            except OSError:
                pass
    result["records"] = sorted(set(result["records"])) or ([out_path] if os.path.isfile(out_path) else [])
    if result["errors"]:
        first = sorted(result["errors"].items())[0]
        raise ChannelError(f"LAUNCH_FAILED: party {first[0]} failed: {first[1]}")
    if len(result["summaries"]) < 2:
        raise ChannelError("LAUNCH_FAILED: a party process did not report a result within the timeout")
    return result


def _cli(argv: Optional[List[str]] = None) -> int:   # pragma: no cover (manual use)
    import argparse
    ap = argparse.ArgumentParser(prog="opencrab2-launch", description="Run one three-process OpenCrab v2 session")
    ap.add_argument("--model", default="gpt2")
    ap.add_argument("--n-layers", type=int, default=1)
    ap.add_argument("--prompt-ids", default="464,3139,286,4881")
    ap.add_argument("--n-generate", type=int, default=2)
    ap.add_argument("--policy", default="B4_opencrab")
    ap.add_argument("--contract", default="NC-v2-f16-l40")
    ap.add_argument("--trace-json", default=None, help="path of a trace dict (opencrab2.experiments.traces); default unshaped")
    ap.add_argument("--out-dir", default=None, help="default: raw/launch under the data root")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--threads-per-process", type=int, default=None)
    ap.add_argument("--warm-prime", action="store_true", help="run a priming session first (measured warm request)")
    args = ap.parse_args(argv)
    if not args.out_dir:
        from opencrab2.experiments import schema
        args.out_dir = str(schema.experiments_root() / "raw" / "launch")
    trace = None
    if args.trace_json:
        with open(args.trace_json, "r", encoding="utf-8") as fh:
            trace = json.load(fh)
    cfg = SessionConfig(model=args.model, n_layers=args.n_layers, prompt_ids=[int(x) for x in args.prompt_ids.split(",")],
                        n_generate=args.n_generate, policy=args.policy, trace_id=trace["trace_id"] if trace else "unshaped",
                        seed=args.seed, contract=contract_by_name(args.contract))
    res = launch_two_party(cfg, trace, args.out_dir, threads_per_process=args.threads_per_process,
                           warm_prime=args.warm_prime)
    sys.stdout.write(json.dumps({"records": res["records"], "summaries": res["summaries"]}, indent=1) + "\n")
    return 0


if __name__ == "__main__":   # pragma: no cover
    sys.exit(_cli())


